// The overlay page's only way to talk to the main process.
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('slop', {
  model: () => ipcRenderer.invoke('model'),
  wasm: () => ipcRenderer.invoke('wasm'),
  settings: () => ipcRenderer.invoke('settings'),
  wallpaper: () => ipcRenderer.invoke('wallpaper'),
  budget: () => ipcRenderer.invoke('budget'),
  onBudget: (cb) => ipcRenderer.on('budget', (_e, lv) => cb(lv)),
  display: () => ipcRenderer.invoke('display'),
  onSettings: (cb) => ipcRenderer.on('settings', (_e, s) => cb(s)),
  clickable: (on) => ipcRenderer.send('clickable', on),
  status: (s) => ipcRenderer.send('status', s),
  log: (...a) => ipcRenderer.send('log', ...a),
  rate: (meta, bytes) => ipcRenderer.send('rate', meta, bytes),
  rated: () => ipcRenderer.invoke('rated'),
  unrate: () => ipcRenderer.send('unrate'),
  feedbackMode: (on) => ipcRenderer.send('feedback-mode', on),
  feedback: (meta, bytes) => ipcRenderer.send('feedback', meta, bytes),
  foregroundApp: () => ipcRenderer.invoke('foreground-app'),
  applySetting: (action, direction, app) => ipcRenderer.invoke('apply-setting', action, direction, app),
  undoSetting: (token) => ipcRenderer.invoke('undo-setting', token),
  llmRead: (text) => ipcRenderer.invoke('llm-read', text),
  onCheckFiles: (cb) => ipcRenderer.on('check-files', (_e, files) => cb(files)),
  checkFilesDone: (r) => ipcRenderer.send('check-files-done', r),
  setPaused: (v) => ipcRenderer.send('set-paused', v),
  quit: () => ipcRenderer.send('quit'),
});
