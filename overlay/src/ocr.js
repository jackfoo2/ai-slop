// Reading text in and around pictures, fully offline (Tesseract, Apache-2.0), to catch visible AI
// watermarks ("Imagined with AI", "KLING AI", "Sora"...) and site labels ("AI info", #aiart...).
import { createWorker } from 'tesseract.js';

let ready = null;
export function startOcr(log) {
  ready ??= (async () => {
    const base = new URL('tesseract/', location.href).href;
    const w = await createWorker('eng', 1, { workerPath: base + 'worker.min.js', corePath: base, langPath: base + 'lang', gzip: true, cacheMethod: 'none', workerBlobURL: false });
    await w.setParameters({ tessedit_pageseg_mode: '11' }); // sparse text: scattered words, not paragraphs
    log('text reading ready');
    return w;
  })().catch((e) => { log('text reading failed to start: ' + (e?.message || e)); ready = null; throw e; });
  return ready;
}
export async function readText(canvas) {
  const w = await ready;
  const { data } = await w.recognize(canvas);
  return data.text || '';
}

// ---- what counts
// Inside the picture (watermarks). Short tool names must be whole words.
const WATERMARK = ['imagined with ai', 'made with ai', 'generated with ai', 'generated by ai', 'ai generated', 'created with ai', 'meta ai', 'kling ai',
  'hailuo', 'midjourney', 'dall-e', 'leonardo ai', 'adobe firefly', 'ideogram', 'openai', 'chatgpt', 'canva ai', 'luma ai', 'dreamina', 'stable diffusion',
  'nightcafe', 'starryai', 'playground ai', 'image creator', 'synthesia', 'heygen', 'minimax'];
const WATERMARK_WORDS = ['sora', 'veo', 'kling', 'pika', 'grok', 'vidu', 'krea', 'jimeng'];
// Around the picture (site labels, captions). Phrases only, no bare tool names.
const LABEL = ['ai info', 'ai generated', 'ai-generated', 'made with ai', 'generated with ai', 'generated by ai', 'created with ai', 'imagined with ai',
  'altered or synthetic', 'synthetic content', '#aiart', '#aiartwork', '#aigenerated', '#aiimage', '#midjourney', '#stablediffusion', '#dalle',
  '#sora', '#aiartcommunity', '#generativeai', '#aiphotography', '#aivideo'];

/** Lowercase, fix common misreads, keep letters, digits, # and single spaces. */
export function normalize(t) {
  return ` ${String(t).toLowerCase().replace(/[|]/g, 'l').replace(/[‐-―]/g, '-').replace(/[^a-z0-9#\- ]+/g, ' ').replace(/\s+/g, ' ').trim()} `;
}
function lev(a, b, max) {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i]; let best = i;
    for (let j = 1; j <= b.length; j++) { cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)); if (cur[j] < best) best = cur[j]; }
    if (best > max) return max + 1;
    prev = cur;
  }
  return prev[b.length];
}
/** Find a phrase in text, forgiving a misread letter or two in longer phrases. */
function hasPhrase(text, p) {
  const fix = (s) => s.replace(/0/g, 'o').replace(/1/g, 'l');
  const t = fix(text), q = fix(p);
  if (t.includes(q)) return true;
  const max = q.length >= 12 ? 2 : q.length >= 7 ? 1 : 0;
  if (!max) return false;
  for (let i = 0; i + q.length - 1 <= t.length; i++) for (const L of [q.length - 1, q.length, q.length + 1]) if (lev(t.slice(i, i + L), q, max) <= max) return true;
  return false;
}
/** { kind: 'watermark' | 'label', word } or null. */
export function matchAiText(inside, around) {
  const a = normalize(inside), b = normalize(around);
  for (const p of WATERMARK) if (hasPhrase(a, p)) return { kind: 'watermark', word: p };
  for (const w of WATERMARK_WORDS) if (a.includes(` ${w} `)) return { kind: 'watermark', word: w };
  for (const p of LABEL) if (hasPhrase(b, p) || hasPhrase(a, p)) return { kind: 'label', word: p };
  return null;
}
